"""E6 (pod): assemble the row sources e6_codes.py tokenises (E6_PLAN.md §3.2, 3.6, 3.7).

  python e6/e6_pod_rows.py

  pseudo_v1/rows.jsonl   E1b's Base pseudo-zh, regenerated by e1/e1_pseudo.py in the E1 bundle context
                         (/workspace/bd1: 49 names, same texts, seeds, gates, cap), kept for the 37 v1 rows
                         only. Per-voice kept counts are compared with E1's report (disclosure, not corrected).
  vc/vc_rows.jsonl       E5's VC rows minus mygo_tomori and mujica_sakiko_tsuki (their converters were built
                         on v1-channel audio of rows that now change) + E6's VC rows for the four new roles.
  bundle/nv_rows.jsonl   [nv] rows (written locally by e6_rows.py; checked here).
Audio paths written on Windows are moved under BD_POD.
"""
from __future__ import annotations

import json
import os
from collections import Counter
from pathlib import Path

ROOT = Path(os.environ.get("BD_POD", "/workspace/bd"))
BD1 = Path(os.environ.get("BD_POD_E1", "/workspace/bd1"))
LOCAL = "E:\\STEINS;GATEVoice\\bangdream"
DROP_VC = {"mygo_tomori", "mujica_sakiko_tsuki"}
TOL = 3


def read(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def write(p: Path, rows: list[dict]) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


def podpath(a: str) -> str:
    return str(ROOT / Path(a.replace(LOCAL + "\\", "").replace("\\", "/")))


def main() -> None:
    sel = json.loads((ROOT / "bundle" / "rows_e6.json").read_text())
    keep = set(sel["v1_kept"])
    e1 = read(BD1 / "pseudo" / "pseudo_rows.jsonl")
    if not e1:
        raise SystemExit("E1b-recipe pseudo rows missing (run e1/e1_pseudo.py with BD_POD=/workspace/bd1)")
    new = json.loads((BD1 / "pseudo" / "report.json").read_text(encoding="utf-8"))
    old = json.loads((ROOT / "e6up" / "e1_pseudo_report.json").read_text(encoding="utf-8"))
    diff = {k: new[k]["kept"] - old[k]["kept"] for k in old if k in keep and new[k]["kept"] != old[k]["kept"]}
    pv1 = [r for r in e1 if r["speaker"] in keep]
    write(ROOT / "pseudo_v1" / "rows.jsonl", pv1)
    print(f"[e6_rows] pseudo_v1: {len(pv1)} rows for {len({r['speaker'] for r in pv1})} v1 rows "
          f"(E1b, same rows: {sum(v['kept'] for k, v in old.items() if k in keep)}); per-voice differences {diff or 'none'}; "
          f"off by > {TOL}: {[k for k, d in diff.items() if abs(d) > TOL] or 'none'}", flush=True)

    vc5 = [r for r in read(ROOT / "e6up" / "e5_rvc_rows.jsonl") if r["speaker"] not in DROP_VC]
    vc6 = read(ROOT / "e6up" / "e6_rvc_rows.jsonl")
    vc = []
    for r in vc5 + vc6:
        vc.append({**r, "audio": podpath(r["audio"])})
    missing = [r["audio"] for r in vc if not os.path.exists(r["audio"])]
    if missing:
        raise SystemExit(f"{len(missing)} VC audio files missing, e.g. {missing[:3]}")
    ids = Counter(r["id"] for r in vc + pv1)
    if any(v > 1 for v in ids.values()):
        raise SystemExit(f"duplicate ids: {[k for k, v in ids.items() if v > 1][:5]}")
    write(ROOT / "vc" / "vc_rows.jsonl", vc)
    print(f"[e6_rows] VC rows: E5 kept {len(vc5)}, E6 {len(vc6)}: {dict(sorted(Counter(r['speaker'] for r in vc).items()))}", flush=True)

    nv = read(ROOT / "bundle" / "nv_rows.jsonl")
    missing = [r["audio"] for r in nv if not os.path.exists(r["audio"])]
    if missing:
        raise SystemExit(f"{len(missing)} nv audio files missing, e.g. {missing[:3]}")
    print(f"[e6_rows] nv rows: {len(nv)} over {len({r['speaker'] for r in nv})} rows", flush=True)


if __name__ == "__main__":
    main()
